CREATE TABLE products (
  id TEXT PRIMARY KEY,
  retailer TEXT NOT NULL CHECK (retailer IN ('Amazon','Flipkart')),
  retailer_id TEXT NOT NULL,
  title TEXT NOT NULL,
  category TEXT NOT NULL,
  description TEXT NOT NULL,
  image TEXT NOT NULL,
  url TEXT NOT NULL,
  mrp BIGINT NOT NULL CHECK (mrp > 0 AND mrp <= 9007199254740991),
  demo SMALLINT NOT NULL DEFAULT 1 CHECK (demo IN (0,1))
);

CREATE TABLE daily_prices (
  product_id TEXT NOT NULL REFERENCES products(id),
  day TEXT NOT NULL,
  price BIGINT NOT NULL CHECK (price > 0 AND price <= 9007199254740991),
  observed_at TEXT NOT NULL,
  source TEXT NOT NULL CHECK (source IN ('demo','feed')),
  PRIMARY KEY (product_id,day,source)
);
CREATE INDEX prices_day_idx ON daily_prices(day);

CREATE TABLE clicks (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  product_id TEXT NOT NULL REFERENCES products(id),
  clicked_at TEXT NOT NULL
);
